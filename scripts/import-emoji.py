#!/usr/bin/env python3
"""Imports the Mattermost webapp's emoji list into
crates/matty-app/src/emoji.tsv, so Matty knows every emoji, name and skin
tone the official client does (a reaction called
`badminton_racquet_and_shuttlecock` is 🏸 in both).

    git clone --depth 1 https://github.com/mattermost/mattermost.git /tmp/mm
    scripts/import-emoji.py /tmp/mm

Each line is one of:

    E <tab> category <tab> glyph <tab> names <tab> label <tab> tone names
    T <tab> glyph <tab> names

An `E` line is a picker emoji, in the webapp's order: its Mattermost names
(the first is the one reactions use), its Unicode name for search, and the
names of its five single-tone versions, lightest first, when it has them.
A `T` line is any other version in a skin tone, which reactions and
messages can still name. Names are separated by spaces.

The webapp is Apache-2.0 licensed (see NOTICE). Only the Python standard
library is used.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

SOURCE = "webapp/channels/src/utils/emoji.json"
OUT = Path(__file__).resolve().parent.parent / "crates/matty-app/src/emoji.tsv"
TONES = ["1F3FB", "1F3FC", "1F3FD", "1F3FE", "1F3FF"]
CATEGORIES = {
    "smileys-emotion",
    "people-body",
    "animals-nature",
    "food-drink",
    "travel-places",
    "activities",
    "objects",
    "symbols",
    "flags",
}


def glyph(unified: str) -> str:
    return "".join(chr(int(point, 16)) for point in unified.split("-"))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("checkout", type=Path, help="a mattermost/mattermost checkout")
    args = parser.parse_args()
    emoji = json.loads((args.checkout / SOURCE).read_text(encoding="utf-8"))
    commit = subprocess.run(
        ["git", "-C", str(args.checkout), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
        check=False,
    ).stdout.strip()

    toned = {e["unified"]: e for e in emoji if "skins" in e}
    used_tones: set[str] = set()
    lines = [
        f"# Generated by scripts/import-emoji.py from mattermost/mattermost {commit or 'unknown'}",
        f"# {SOURCE}. Do not edit by hand.",
    ]
    for entry in emoji:
        if "skins" in entry or entry["category"] not in CATEGORIES:
            continue
        variations = entry.get("skin_variations") or {}
        tones = []
        for tone in TONES:
            variation = variations.get(tone) or variations.get(f"{tone}-{tone}")
            version = variation and toned.get(variation["unified"])
            if not version:
                break
            tones.append(version["short_name"])
            used_tones.add(version["unified"])
        if len(tones) != len(TONES):
            tones = []
        names = " ".join(entry["short_names"])
        label = (entry.get("name") or "").lower()
        lines.append(
            "\t".join(["E", entry["category"], glyph(entry["unified"]), names, label, " ".join(tones)])
        )
    for unified, entry in toned.items():
        lines.append("\t".join(["T", glyph(unified), " ".join(entry["short_names"])]))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(lines) - 2} emoji to {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
